def glyph_name(ch):
    return "space" if ch == " " else f"uni{ord(ch):04X}"


def draw(rows):
    pen = TTGlyphPen(None)
    any_px = False
    for r, row in enumerate(rows):
        y_top = (7 - r) * PX
        x = 0
        while x < len(row):
            if row[x] == "#":
                x0 = x
                while x < len(row) and row[x] == "#":
                    x += 1
                # clockwise contour (TrueType outer contours are clockwise)
                pen.moveTo((x0 * PX, y_top))
                pen.lineTo((x * PX, y_top))
                pen.lineTo((x * PX, y_top - PX))
                pen.lineTo((x0 * PX, y_top - PX))
                pen.closePath()
                any_px = True
            else:
                x += 1
    return pen.glyph(), any_px


def build():
    chars = [" "] + sorted(G.keys())
    names = [".notdef"] + [glyph_name(c) for c in chars]
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap({ord(c): glyph_name(c) for c in chars})
    glyphs, metrics = {}, {}
    empty = TTGlyphPen(None).glyph()
    glyphs[".notdef"] = empty
    metrics[".notdef"] = (6 * PX, 0)
    for c in chars:
        if c == " ":
            glyphs["space"] = empty
            metrics["space"] = (4 * PX, 0)
            continue
        rows = G[c]
        g, _ = draw(rows)
        w = max(len(r) for r in rows)
        glyphs[glyph_name(c)] = g
        metrics[glyph_name(c)] = ((w + 1) * PX, 0)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=ASC * PX, descent=-DESC * PX)
    fb.setupNameTable({"familyName": "UltraPixel", "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=ASC * PX, sTypoDescender=-DESC * PX, usWinAscent=ASC * PX, usWinDescent=DESC * PX)
    fb.setupPost()
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    fb.save(OUT)


if __name__ == "__main__":
    build()
